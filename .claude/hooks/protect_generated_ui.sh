#!/usr/bin/env bash
# PreToolUse guard: index.html and ui/index.html are compiled artifacts of
# scripts/build_purged_ui.py (AGENTS.md §6.1). Block direct Edit/Write on them.
set -euo pipefail

root="${CLAUDE_PROJECT_DIR:-$(pwd)}"
file="$(/usr/bin/env jq -r '.tool_input.file_path // .tool_input.notebook_path // empty')"
[ -z "$file" ] && exit 0

case "$file" in
  /*) abs="$file" ;;
  *)  abs="$root/$file" ;;
esac

if [ "$abs" = "$root/index.html" ] || [ "$abs" = "$root/ui/index.html" ]; then
  echo "Blocked: $file is generated by scripts/build_purged_ui.py (AGENTS.md §6.1). Edit that script and run '.venv/bin/python scripts/build_purged_ui.py' from the repo root instead." >&2
  exit 2
fi
exit 0
